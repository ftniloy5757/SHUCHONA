  /// Fuzzy-matches a brand name or generic name against the local DGDA/DIMS dataset.
  static DgdaDrugEntry? findByBrandOrGeneric(String query) {
    final normalized = query.trim().toLowerCase().replaceAll(RegExp(r'[^a-z0-9\s]'), '');
    if (normalized.isEmpty) return null;

    // 1. Exact brand match
    for (final drug in drugs) {
      if (drug.brandName.toLowerCase().replaceAll(RegExp(r'[^a-z0-9\s]'), '') ==
          normalized) {
        return drug;
      }
    }

    // 2. Contains brand match (longest match first)
    final sorted = [...drugs]
      ..sort((a, b) => b.brandName.length.compareTo(a.brandName.length));
    for (final drug in sorted) {
      final brandNorm =
          drug.brandName.toLowerCase().replaceAll(RegExp(r'[^a-z0-9\s]'), '');
      if (normalized.contains(brandNorm) || brandNorm.contains(normalized)) {
        return drug;
      }
    }

    // 3. Generic name match
    for (final drug in drugs) {
      final genNorm =
          drug.genericName.toLowerCase().replaceAll(RegExp(r'[^a-z0-9\s]'), '');
      if (normalized.contains(genNorm) || genNorm.contains(normalized)) {
        return drug;
      }
    }
    return null;
  }

  /// Finds the lowest-cost DGDA-approved equivalent matching the EXACT generic API & strength.
  static DgdaDrugEntry? findCheaperGenericAlternative(DgdaDrugEntry prescribed) {
    final matches = drugs.where((d) {
      if (d.id == prescribed.id) return false;
      final sameGeneric =
          d.genericName.toLowerCase() == prescribed.genericName.toLowerCase();
      final sameStrength =
          d.strength.toLowerCase() == prescribed.strength.toLowerCase();
      return sameGeneric && sameStrength && d.unitPriceBdt < prescribed.unitPriceBdt;
    }).toList();

    if (matches.isEmpty) return null;
    matches.sort((a, b) => a.unitPriceBdt.compareTo(b.unitPriceBdt));
    return matches.first;
  }
